import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {BrowserProvider,ContractFactory,id} from 'ethers';
import {compileProduction} from '../../src/worker/production-build.mjs';
import {compute,QIANQI_RULES} from '../../src/draws/short-outcome.mjs';
process.env.HARDHAT_CONFIG=resolve('tests/contracts/production-worker-hardhat.config.cjs');
const {default:hre}=await import('hardhat');
const provider=new BrowserProvider(hre.network.provider,undefined,{cacheTimeout:-1}),signer=await provider.getSigner(0);
const source='tests/contracts/IGWMonthlyFixtures.sol',build=compileProduction({[source]:{content:readFileSync(source,'utf8')}});
const deploy=async(file,name,args=[])=>{const a=build.contracts[file][name],c=await new ContractFactory(a.abi,a.evm.bytecode.object,signer).deploy(...args);await c.waitForDeployment();return c;};
const tx=async p=>(await p).wait(),quote=await deploy('tests/contracts/Fixtures.sol','TestUSDG');
const interval=2592000,program=await deploy(source,'IGWMonthlyHarness',[{asset:quote.target,operator:await signer.getAddress(),instance:id('monthly-igw-test'),interval,minimumFund:100,minimumUnit:1},[1],{lead:3600,clockLag:30,clockAhead:30,finalizedLag:1800,beaconLag:30}]);
await tx(quote.mint(await signer.getAddress(),100));await tx(quote.approve(program.target,100));await tx(program.fund(100));
const participant={wallet:await (await provider.getSigner(1)).getAddress(),firstAttempt:1,lastAttempt:1};
const checkpoint=async()=>{const b=await provider.getBlock('latest');return {number:b.number,blockHash:b.hash,timestamp:b.timestamp,ledgerHash:id('ledger'+b.number)};};
await assert.rejects(program.freeze([participant],await checkpoint()));
await hre.network.provider.send('evm_setNextBlockTimestamp',[Number(await program.lastTerminal())+interval]);await hre.network.provider.send('evm_mine');
await tx(program.freeze([participant],await checkpoint()));
const d=await program.draws(1);let seed;
for(let n=0;n<1000;n++){seed=id('no-winner-'+n);if(compute(d.context,seed,[participant],QIANQI_RULES,[100n]).winners.length===0)break;if(n===999)throw Error('No losing vector');}
await tx(program.testSeed(seed));await tx(program.settle([participant]));
assert.equal(await program.freeFund(),100n);assert.equal(await program.liabilities(),0n);assert.equal(await program.consumedThrough(participant.wallet),1n);
await assert.rejects(program.settle([participant]));
const terminal=Number(await program.lastTerminal());participant.firstAttempt=2;participant.lastAttempt=2;
await hre.network.provider.send('evm_setNextBlockTimestamp',[terminal+interval-2]);await hre.network.provider.send('evm_mine');
await assert.rejects(program.freeze([participant],await checkpoint()));
await hre.network.provider.send('evm_setNextBlockTimestamp',[terminal+interval]);await hre.network.provider.send('evm_mine');
await tx(program.freeze([participant],await checkpoint()));
assert.equal(await program.cycle(),2n);assert.equal(await program.reserved(),100n);
console.log('PASS monthly IGW: interval, no-winner settlement, consumed tickets, full carry, no double settlement, next 30-day cycle');
console.log('LIMIT deterministic test seed; worker rehearsal separately verifies historical BLS flow');
